import { expect, test } from '../vendor/calccanvas/node_modules/@playwright/test/index.mjs';

test('opens Fin Plate, updates the drawing and reopens an exported design', async ({ page }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('./');
  const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Fin Plate Connection' }) });
  await card.getByRole('link', { name: /Open tool|New design/ }).click();
  const section = page.getByRole('textbox', { name: 'Section', exact: true });
  await expect(section).toHaveValue('UB 533x210x92');
  await expect(page.getByLabel('Web thickness (mm)')).toHaveValue('10.1');
  await page.getByRole('button', { name: 'Browse sections' }).click();
  const library = page.getByRole('dialog', { name: 'Steel section library' });
  const family = library.getByLabel('Section family');
  await expect(family.getByRole('option')).toHaveText(['All I/H sections', 'UB', 'UC', 'IPE', 'HEA', 'HEB', 'HEM', 'W']);
  const search = library.getByRole('searchbox', { name: 'Search sections' });
  await family.selectOption('UC');
  await search.fill('UB457×191×74');
  await expect(library.getByText('No matching sections.')).toBeVisible();
  await family.selectOption('UB');
  await library.getByRole('button', { name: 'UB 457x191x74', exact: true }).click();
  await expect(library).toBeHidden();
  await expect(section).toHaveValue('UB 457x191x74');
  await expect(page.getByLabel('Web thickness (mm)')).toHaveValue('9');
  await page.getByRole('button', { name: 'Load 50° skew preset' }).click();
  await expect(page.locator('#geometry-summary')).toContainText('70.01 kNm');
  await expect(page.locator('#connection-drawing circle')).toHaveCount(10);
  await expect(page.getByRole('img', { name: 'Connection plan' })).toBeVisible();
  await expect(page.getByRole('img', { name: 'Connection elevation' })).toBeVisible();
  await expect(page.getByText('Beam cross-section', { exact: true })).toHaveCount(0);
  await expect(page.locator('#connection-plan .beam-overlap')).toBeAttached();
  await expect(page.locator('#plan-warning')).toContainText('Overlap');
  await expect(page.locator('#detailing-warning')).toBeVisible();
  await page.getByLabel('Vertical bolt columns').selectOption('3');
  await expect(page.locator('#connection-drawing circle')).toHaveCount(15);
  await expect(page.locator('#checks')).toContainText('43.0%');
  await page.getByRole('tab', { name: 'Detailed calculation' }).click();
  const calculation = page.getByRole('tabpanel', { name: 'Detailed calculation' });
  await expect(calculation.locator('.fin-equation[data-latex*="70.01"] > *').first()).toBeVisible();
  await expect(calculation.getByRole('heading', { name: /Fin-plate bearing/ })).toBeVisible();
  await expect(calculation.getByRole('heading', { name: /Bolt shear/ })).toBeVisible();
  await expect(calculation.getByText(/UR means utilization ratio/)).toBeVisible();
  await expect(calculation.getByText(/The negative clearance means the beam end crosses/)).toBeVisible();
  await expect(calculation.getByText(/Calculate bolt shear resistance using bolt strength/)).toBeVisible();
  await expect(calculation.getByText(/Bolt \d+ governs with .*kN demand and .*kN resistance/)).toBeVisible();
  await expect(calculation.locator('.fin-calculation-list li:not(:has(p))')).toHaveCount(0);
  await page.getByLabel('ULS shear (kN)').fill('250');
  await expect(calculation.locator('.fin-equation[data-latex*="58.34"] > *').first()).toBeVisible();
  await page.getByLabel('ULS shear (kN)').fill('300');
  await page.getByRole('tab', { name: 'Detailed calculation' }).press('ArrowLeft');
  await expect(page.getByRole('tabpanel', { name: 'Bolt forces and utilization' })).toBeVisible();
  await expect(page.getByRole('columnheader', { name: 'UR' })).toBeVisible();
  await expect(page.locator('#checks tr[data-governing="true"]')).toContainText('Fin-plate bearing');
  await page.getByText('Compare bolt columns', { exact: true }).click();
  await expect(page.locator('#layout-results tr')).toHaveCount(3);
  await expect(page.getByRole('img', { name: 'Connection plan' }).getByText('50°')).toBeVisible();
  await page.getByRole('button', { name: 'Edit bolt coordinates' }).click();
  await page.getByLabel('Bolt 1 X', { exact: true }).fill('75');
  await page.getByRole('button', { name: 'Apply positions' }).click();
  await expect(page.locator('#details')).toContainText('Coordinate layout');
  await page.getByRole('button', { name: 'Use regular grid' }).click();
  await expect(page.locator('#details')).not.toContainText('Coordinate layout');

  const shell = page.getByRole('navigation', { name: 'Design workspace' });
  await shell.getByLabel('Design name').fill('Fin plate browser check');
  await shell.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(shell.getByText('Design saved.')).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Vertical bolt columns')).toHaveValue('3');
  const savedUrl = page.url();
  await page.goto('./#designs');
  const saved = page.locator('#design-list article').filter({ hasText: 'Fin plate browser check' });
  const download = page.waitForEvent('download');
  await saved.getByRole('button', { name: 'Save .mfp', exact: true }).click();
  const design = await download;
  expect(design.suggestedFilename()).toMatch(/\.mfp$/);
  const file = testInfo.outputPath(design.suggestedFilename());
  await design.saveAs(file);
  await page.goto('./#tools');
  await card.locator('input[type="file"]').setInputFiles(file);
  await expect(page).toHaveURL(/t\/fin-plate\/\?design=/);
  expect(page.url()).not.toBe(savedUrl);
  await expect(shell.getByLabel('Design name')).toHaveValue('Fin plate browser check');
  await shell.getByRole('button', { name: 'Report', exact: true }).click();
  await expect(page).toHaveURL(/calc\/\?report=/);
  await expect(page.getByTestId('canvas').getByText('Elastic bolt forces (kN)', { exact: true })).toBeVisible({ timeout: 20000 });
  expect(errors).toEqual([]);
});

test('switches support families and draws and checks a beam notch', async ({ page }) => {
  await page.goto('./');
  await page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Fin Plate Connection' }) })
    .getByRole('link', { name: /Open tool|New design/ }).click();
  const joint = page.getByLabel('Joint type');
  const attachment = page.getByLabel('Column attachment');
  const top = page.getByLabel('Top notch depth (mm)');
  await expect(joint).toHaveValue('beam-beam');
  await expect(attachment).toBeHidden();
  await page.getByLabel('Horizontal bolt rows').fill('4');
  await page.getByLabel('Beam laterally restrained').check();
  await top.fill('45');
  await page.getByLabel('Notch length from beam end (mm)').fill('180');
  await expect(page.getByRole('img', { name: 'Connection elevation' }).getByText('Top notch 45.0 mm')).toBeVisible();
  await expect(page.locator('#checks')).toContainText('Notched web block tearing');
  await expect(page.locator('#checks')).toContainText('Bending at notch shoulder');
  await page.getByRole('tab', { name: 'Detailed calculation' }).click();
  await expect(page.getByRole('heading', { name: 'P358 Check 5 · Bending at notch shoulder' })).toBeVisible();
  await joint.selectOption('beam-column');
  await expect(top).toBeHidden();
  await expect(attachment.getByRole('option')).toHaveText([
    'I/H column web', 'I/H column flange', 'SHS outer face', 'RHS outer face', 'CHS outer face',
  ]);
  await attachment.selectOption('chs');
  await expect(page.getByRole('img', { name: 'Connection plan' }).getByText('CHS outer face')).toBeVisible();
  await expect(page.locator('#checks')).not.toContainText('notch shoulder');
  await joint.selectOption('beam-beam');
  await expect(top).toHaveValue('45');
  await expect(page.locator('#checks')).toContainText('Bending at notch shoulder');
});

test('formats and prints the live calculation worksheet with the correct applicability', async ({ page }) => {
  await page.goto('./');
  await page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Fin Plate Connection' }) })
    .getByRole('link', { name: /Open tool|New design/ }).click();
  await page.getByLabel('Joint type').selectOption('beam-column');
  await page.getByRole('tab', { name: 'Detailed calculation' }).click();
  const sheet = page.locator('.fin-sheet');
  await expect(sheet.getByRole('heading', { name: 'Beam to column · I/H column flange · Square connection' })).toBeVisible();
  await expect(sheet.getByRole('img', { name: 'Calculation plan' })).toBeVisible();
  await expect(sheet.getByRole('img', { name: 'Calculation elevation' })).toBeVisible();
  await expect(sheet.locator('[data-check="10"]')).toContainText('Not applicable');
  await page.getByLabel('Column attachment').selectOption('column-web');
  await expect(sheet.locator('[data-check="10"]')).toContainText('Open');
  await page.getByLabel('Joint type').selectOption('beam-beam');
  await page.getByLabel('Horizontal bolt rows').fill('4');
  await page.getByLabel('Top notch depth (mm)').fill('45');
  await page.getByLabel('Bottom notch depth (mm)').fill('45');
  await page.getByLabel('Notch length from beam end (mm)').fill('180');
  await expect(sheet.getByRole('heading', { name: 'Beam to beam · Double notch · Square connection' })).toBeVisible();
  await expect(sheet.locator('[data-check="5"]')).toContainText('Calculated');
  await page.getByText('Skew and eccentricity', { exact: true }).click();
  await page.getByLabel('Plan skew (°)').fill('15');
  await expect(sheet.getByRole('heading', { name: 'Beam to beam · Double notch · Skewed 15°' })).toBeVisible();
  await expect(sheet.locator('[data-check="5"]')).toContainText('Open');
  await page.emulateMedia({ media: 'print' });
  await expect(sheet).toBeVisible();
  await expect(page.locator('main.fin-layout')).toBeHidden();
  await expect(sheet.getByRole('button', { name: 'Print calculation' })).toBeHidden();
});
