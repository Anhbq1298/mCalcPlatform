import { expect, test } from '../vendor/calccanvas/node_modules/@playwright/test/index.mjs';

test('opens Fin Plate, updates the drawing and reopens an exported design', async ({ page }, testInfo) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('./');
  const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Fin Plate Connection' }) });
  await card.getByRole('link', { name: /Open tool|New design/ }).click();
  const section = page.getByRole('combobox', { name: 'Section', exact: true });
  await expect(section).toHaveValue('UB 533x210x92');
  await expect(page.getByLabel('Web thickness (mm)')).toHaveValue('10.1');
  await section.fill('UB457×191×74');
  await expect(page.getByLabel('Web thickness (mm)')).toHaveValue('9');
  await page.getByRole('button', { name: 'Load 50° skew preset' }).click();
  await expect(page.locator('#geometry-summary')).toContainText('70.01 kNm');
  await expect(page.locator('#connection-drawing circle')).toHaveCount(10);
  await page.getByLabel('Vertical bolt columns').selectOption('3');
  await expect(page.locator('#connection-drawing circle')).toHaveCount(15);
  await expect(page.locator('#checks')).toContainText('43.0%');
  await page.getByText('Compare bolt columns', { exact: true }).click();
  await expect(page.locator('#layout-results tr')).toHaveCount(3);
  await page.getByRole('combobox', { name: 'View', exact: true }).selectOption('plan');
  await expect(page.getByRole('img').getByText('50°')).toBeVisible();
  await page.getByRole('button', { name: 'Edit bolt coordinates' }).click();
  await page.getByLabel('Bolt 1 X', { exact: true }).fill('75');
  await page.getByRole('button', { name: 'Apply positions' }).click();
  await expect(page.locator('#details')).toContainText('Coordinate layout');
  await page.getByRole('button', { name: 'Use regular grid' }).click();
  await expect(page.locator('#details')).not.toContainText('Coordinate layout');

  const shell = page.getByRole('navigation', { name: 'Design workspace' });
  await shell.getByLabel('Design name').fill('Fin plate browser check');
  await shell.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(shell.getByText('Design saved.')).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Vertical bolt columns')).toHaveValue('3');
  const savedUrl = page.url();
  await page.goto('./#designs');
  const saved = page.locator('#design-list article').filter({ hasText: 'Fin plate browser check' });
  const download = page.waitForEvent('download');
  await saved.getByRole('button', { name: 'Save .mfp', exact: true }).click();
  const design = await download;
  expect(design.suggestedFilename()).toMatch(/\.mfp$/);
  const file = testInfo.outputPath(design.suggestedFilename());
  await design.saveAs(file);
  await page.goto('./#tools');
  await card.locator('input[type="file"]').setInputFiles(file);
  await expect(page).toHaveURL(/t\/fin-plate\/\?design=/);
  expect(page.url()).not.toBe(savedUrl);
  await expect(shell.getByLabel('Design name')).toHaveValue('Fin plate browser check');
  await shell.getByRole('button', { name: 'Report', exact: true }).click();
  await expect(page).toHaveURL(/calc\/\?report=/);
  await expect(page.getByTestId('canvas').getByText('Elastic bolt forces (kN)', { exact: true })).toBeVisible({ timeout: 20000 });
  expect(errors).toEqual([]);
});
